package eu.amadeos.games.cruise.domain;

/** What a region sounds like besides the engine: the loop under everything and the calls now and then. */
public enum Ambience {
    /** Leaves in the wind, songbirds, a woodpecker now and then. */
    FOREST,
    /** Crickets and larks over the fields. */
    FIELDS,
    /** Surf on the beach, gulls. */
    COAST,
    /** A warm wind howling through the rocks, a hawk's cry. */
    CANYON,
    /** A cold wind, cowbells on the alpine meadows. */
    ALPINE,
    /** The hum of a city at night, a far horn. */
    CITY,
    /** A soft chord and chimes. */
    DREAM,
    /** High wind and bells. */
    SKY
}
