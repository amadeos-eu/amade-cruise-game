package eu.amadeos.games.cruise.domain;

/** Animals and other moving things beside the road. */
public enum LifeKind {
    /** Grazes at the edge of the forest at dawn and dusk; leaps away when a car comes near. */
    DEER,
    /** Stand on a pasture with a bell. */
    COWS,
    SHEEP,
    /** A flock crossing over the road. */
    BIRDS,
    /** Circles high above. */
    HAWK,
    GULLS,
    /** Drifts far to the side. */
    BALLOON,
    /** Runs on a track beside the road, faster or slower than the cars. */
    TRAIN,
    /** Sails on the sea. */
    BOAT,
    /** Small lights over the grass. */
    FIREFLIES,
    /** Paper lanterns rising slowly. */
    LANTERNS,
    /** A whale swimming through the sky. */
    SKY_WHALE
}
